import test from 'node:test';
import assert from 'node:assert/strict';
import { validateCamp } from './rules.mjs';
import { createSurvPlay } from './survplay.mjs';
import { FORMAL_OPTIONS } from './balance-probe.mjs';
import { CURRENT_EVENT_RULES } from './rng.mjs';
const w = createSurvPlay(7, { ...FORMAL_OPTIONS, eventRulesVersion: CURRENT_EVENT_RULES }).world;
test('ARCH4-07 未知 camp_* 被 validateCamp 拒绝', () => assert.equal(validateCamp(w, { kind: 'camp_nope' }).code, 'UNKNOWN_CAMP_ACTION'));
test('ARCH4-07 免费退出/睡觉放行', () => assert.equal(validateCamp(w, { kind: 'camp_exit' }), null));
test('ARCH4-07 远距 reach 失败透传', () => assert.equal(validateCamp(w, { kind: 'camp_store', from: [0, 0] }, () => ({ ok: false, code: 'TOO_FAR' })).code, 'TOO_FAR'));
test('ARCH4-07 合法动作 + reach 通过不改变结果', () => assert.equal(validateCamp(w, { kind: 'camp_store', from: [1, 2] }, () => ({ ok: true })), null));
